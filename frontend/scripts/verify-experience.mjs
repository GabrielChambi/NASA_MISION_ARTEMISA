import {chromium} from 'playwright'
import {mkdir,writeFile,readFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'
import assert from 'node:assert/strict'

const base=process.env.LUNAR_ORACLE_TEST_URL||'http://127.0.0.1:5173/'
const out=new URL('../../artifacts/',import.meta.url)
await mkdir(out,{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true})
const errors=[],checks=[],diagnostics={}
const watch=page=>page.on('pageerror',error=>errors.push(error.message))
const visibleCopilot=page=>page.locator('.mission-copilot:visible')
const shoot=(page,name)=>page.screenshot({path:fileURLToPath(new URL(name+'.png',out)),fullPage:true})
const overflow=async page=>assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'No horizontal clipping')
const ready=async page=>{
  await page.getByRole('button',{name:'Analizar todo el polo sur',exact:true}).waitFor()
  await page.waitForFunction(()=>{const button=document.querySelector('.primary-explore');return button&&!button.disabled},null,{timeout:45000})
}
try{
  const page=await browser.newPage({viewport:{width:1500,height:1050},reducedMotion:'reduce'})
  watch(page)
  await page.goto(base,{waitUntil:'networkidle'})
  await ready(page)
  const map=page.getByTestId('polar-map')
  const canvas=map.locator('canvas')
  const box=await map.boundingBox(),canvasBox=await canvas.boundingBox()
  assert.ok(box.width>500&&box.height>400)
  assert.ok(Math.abs(box.height-canvasBox.height)<2,'Canvas fills polar map')
  assert.equal(await page.getByTestId('tactical-cockpit').isVisible(),false,'Detailed cockpit hidden initially')
  assert.equal(await map.locator('.surface-destination').count(),0,'No misleading local destination in initial overview')
  assert.equal(await page.locator('.candidate-card').count(),0)
  const messageIds=await page.locator('.mission-copilot textarea').evaluateAll(nodes=>nodes.map(n=>n.id))
  assert.equal(new Set(messageIds).size,messageIds.length,'Mounted copilots use unique input IDs')
  assert.match(await map.locator('.polar-scope-badge').innerText(),/SIN CLASIFICAR/)
  assert.match(await page.locator('.explorer-coverage').innerText(),/80°S.*90°S/s)
  assert.match(await page.locator('.explorer-coverage').innerText(),/80 m/)
  await overflow(page)
  await shoot(page,'experience-initial-desktop')
  checks.push('Default view is the entire south-polar cap; no local coloured square or landing verdict.')

  const surfaceResponse=await page.request.get(new URL('/api/polar/surface',base).href)
  assert.equal(surfaceResponse.status(),200)
  const surface=await surfaceResponse.json()
  diagnostics.coverage=surface.statistics
  assert.ok(surface.statistics.known_cells>12000,'Regional coverage is not restricted to two local patches')
  await page.getByRole('button',{name:'Analizar todo el polo sur',exact:true}).click()
  await page.locator('.candidate-card').first().waitFor()
  assert.equal(await page.locator('.candidate-card').count(),3)
  assert.match(await map.locator('.polar-scope-badge').innerText(),/EVALUACIÓN REGIONAL/)
  const results=[]
  for(let i=0;i<3;i++){
    await page.locator('.candidate-card').nth(i).click()
    const card=await page.locator('.zone-summary').innerText()
    assert.match(card,/Sin evaluar/)
    assert.match(card,/Requiere detalle/)
    assert.match(card,/Pendiente P95/)
    results.push(card)
  }
  assert.equal(new Set(results).size,3)
  await page.getByRole('button',{name:'Acercar esta zona',exact:true}).click()
  await page.getByRole('button',{name:'Volver a todo el polo',exact:true}).waitFor()
  await shoot(page,'experience-zone-focus')
  await page.getByRole('button',{name:'Volver a todo el polo',exact:true}).click()
  checks.push('Whole-cap analysis produces three calculated candidates, working zone zoom/return and unknown mission visibility.')

  // An ordinary surface click selects another regional zone, without the old outside-coverage error.
  const mapBounds=await canvas.boundingBox()
  await canvas.click({position:{x:mapBounds.width*.5,y:mapBounds.height*.58}})
  await page.waitForTimeout(150)
  assert.equal(await page.locator('.explorer-notice').count(),0)
  assert.match(await page.locator('.zone-summary').innerText(),/TU ZONA SELECCIONADA/)
  const clickedZone=await page.locator('.zone-summary h2').innerText()
  diagnostics.clickedZone=clickedZone
  await shoot(page,'experience-analysis-desktop')
  checks.push('Clicking the regional Moon selects a zone without a local-square coverage error.')

  const copilot=visibleCopilot(page)
  assert.match(await copilot.locator('.copilot-heading small').innerText(),/Guía|Gemini/)
  const replyResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/copilot'&&r.request().method()==='POST')
  await copilot.getByRole('button',{name:'¿Qué era el cuadrado de otro color?',exact:true}).click()
  const reply=await(await replyResponse).json()
  await copilot.locator('.copilot-reply').waitFor()
  assert.equal(reply.mode,'guide','No live model is configured in this QA environment')
  assert.match(await copilot.locator('.reply-mode').innerText(),/SIN MODELO IA/)
  assert.match(await copilot.locator('.copilot-reply').innerText(),/cuadrado era|cobertura del estudio local/i)
  await copilot.getByText('Datos usados en esta respuesta',{exact:true}).click()
  assert.ok(await copilot.locator('.copilot-fact').count()>0)
  await copilot.getByRole('button',{name:'Ver todo el polo',exact:true}).click()
  assert.equal(await map.isVisible(),true)
  await page.locator('.regional-settings summary').click()
  await page.getByLabel('Pendiente regional máxima',{exact:true}).fill('12')
  assert.equal(await page.locator('.candidate-card').count(),0,'Changing regional threshold invalidates candidate results')
  assert.match(await copilot.locator('.stale-advice').innerText(),/Cambiaste/)
  assert.equal(await copilot.locator('.copilot-action').count(),0,'Stale advice cannot apply a previous action')
  await page.getByLabel('Pendiente regional máxima',{exact:true}).fill('10')
  await page.locator('.regional-settings summary').click()
  checks.push('Copilot labels its actual guide mode, explains the former square and exposes evidence plus an explicit map action.')

  await page.getByRole('button',{name:'Abrir estudio detallado',exact:true}).click()
  await page.getByTestId('tactical-cockpit').waitFor({state:'visible'})
  assert.equal(await map.isVisible(),false)
  assert.equal(await visibleCopilot(page).count(),1)
  await page.getByRole('button',{name:/^Analizar Sol y Tierra$/i}).waitFor()
  await page.getByRole('button',{name:'← Todo el polo sur',exact:true}).click()
  assert.equal(await map.isVisible(),true)
  assert.equal(await page.getByTestId('tactical-cockpit').isVisible(),false)
  assert.equal(await page.locator('.zone-summary h2').innerText(),clickedZone)
  assert.equal(await page.locator('.candidate-card').count(),3)
  await page.getByRole('button',{name:'Ver datos y alcance',exact:true}).click()
  assert.match(await page.locator('.polar-method').innerText(),/no garantizan aterrizajes/i)
  assert.match(await page.locator('.polar-method').innerText(),/nodata|desconocidos/)
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'Descargar evaluación regional',exact:true}).click()
  const download=await downloadEvent
  const exportPath=fileURLToPath(new URL('experience-regional-evidence.json',out))
  await download.saveAs(exportPath)
  const evidence=JSON.parse(await readFile(exportPath,'utf8'))
  assert.equal(evidence.scope,'regional-terrain-screening')
  assert.equal(evidence.source_resolution_m,80)
  assert.ok(evidence.assessments.length>12000)
  assert.ok(evidence.assessments.every(c=>['green','yellow','red','unknown'].includes(c.risk)))
  checks.push('Local study is an explicit separate step; returning preserves regional selection, evidence and candidate results.')
  await page.close()

  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1,reducedMotion:'reduce'})
  watch(mobile)
  await mobile.goto(base,{waitUntil:'networkidle'})
  await ready(mobile)
  await overflow(mobile)
  for(const locator of [mobile.getByRole('button',{name:'Analizar todo el polo sur',exact:true}),mobile.getByRole('button',{name:'Evaluación',exact:true}),mobile.getByRole('button',{name:'Relieve',exact:true}),mobile.getByRole('button',{name:/Planifica tu misión/})]){
    const b=await locator.boundingBox()
    assert.ok(b&&b.x>=-1&&b.x+b.width<=391,'Mobile primary control remains in viewport width')
  }
  await mobile.getByRole('button',{name:'Analizar todo el polo sur',exact:true}).click()
  await mobile.locator('.candidate-card').first().waitFor({state:'attached'})
  const mobileCandidates=mobile.locator('details.candidate-list')
  if(await mobileCandidates.count()&&!await mobileCandidates.evaluate(el=>el.open))await mobileCandidates.locator('summary').click()
  diagnostics.mobileCandidatesVisible=await mobile.locator('.candidate-card').first().isVisible()
  assert.equal(diagnostics.mobileCandidatesVisible,true,'Mobile retains suggested zones')
  if(await mobileCandidates.count()&&await mobileCandidates.evaluate(el=>el.open))await mobileCandidates.locator('summary').click()
  const mMap=mobile.getByTestId('polar-map')
  const mBox=await mMap.boundingBox(),mCanvasBox=await mMap.locator('canvas').boundingBox()
  assert.ok(Math.abs(mBox.height-mCanvasBox.height)<2)
  assert.match(await mMap.locator('.polar-scope-badge').innerText(),/REGIONAL/)
  await mMap.scrollIntoViewIfNeeded()
  await shoot(mobile,'experience-mobile')
  await mobile.getByRole('button',{name:/Planifica tu misión/}).click()
  await mobile.getByTestId('tactical-cockpit').waitFor({state:'visible'})
  await overflow(mobile)
  await mobile.getByRole('button',{name:'← Todo el polo sur',exact:true}).click()
  await overflow(mobile)
  await mobile.close()
  checks.push('390 px mobile has a full-height Moon, visible primary controls, no horizontal overflow and a working detail/back path.')

  const failed=await browser.newPage({viewport:{width:1400,height:1000}})
  watch(failed)
  await failed.route('**/api/polar/surface',r=>r.fulfill({status:503,contentType:'application/json',body:JSON.stringify({status:'unavailable',message:'Regional NASA failure regression'})}))
  await failed.goto(base,{waitUntil:'networkidle'})
  const alert=failed.locator('.explorer-left').getByRole('alert')
  await alert.waitFor()
  assert.equal(await failed.getByRole('button',{name:'Analizar todo el polo sur',exact:true}).isDisabled(),true)
  assert.equal(await failed.locator('.candidate-card').count(),0)
  assert.doesNotMatch(await failed.locator('.polar-scope-badge').innerText(),/EVALUACIÓN REGIONAL/)
  assert.doesNotMatch(await failed.locator('.polar-scope-badge').innerText(),/Cargando datos/)
  assert.equal(await failed.locator('.zone-class.green').count(),0)
  await shoot(failed,'experience-failed-data')
  await failed.close()
  checks.push('Regional data failure disables analysis and emits no positive classes or recommendations.')

  assert.deepEqual(errors,[])
  await writeFile(new URL('experience-browser-verification.json',out),JSON.stringify({base,checks,diagnostics,errors},null,2))
  console.log(checks.map(c=>'PASS '+c).join('\n'))
  console.log('DIAGNOSTICS '+JSON.stringify(diagnostics))
}finally{await browser.close()}
