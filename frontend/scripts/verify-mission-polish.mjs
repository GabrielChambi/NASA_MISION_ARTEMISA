import {chromium} from 'playwright'
import {mkdir,writeFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'
import assert from 'node:assert/strict'
const base=process.env.LUNAR_ORACLE_TEST_URL||'http://127.0.0.1:5173/'
const out=new URL('../../artifacts/',import.meta.url)
await mkdir(out,{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true})
const errors=[],checks=[],requests=[]
const watch=page=>{
 page.on('pageerror',e=>errors.push(e.message))
 page.on('response',r=>{if(r.url().includes('/data/polar-detail/'))requests.push({url:new URL(r.url()).pathname,status:r.status()})})
}
const ready=page=>page.waitForFunction(()=>document.querySelector('.primary-explore')&&!document.querySelector('.primary-explore').disabled,null,{timeout:45000})
const shoot=(page,name)=>page.locator('.explorer-map').screenshot({path:fileURLToPath(new URL(name+'.png',out))})
try{
 const page=await browser.newPage({viewport:{width:1500,height:1050},deviceScaleFactor:1,reducedMotion:'reduce'})
 watch(page)
 await page.goto(base,{waitUntil:'networkidle'});await ready(page)
 assert.ok(requests.some(r=>r.url.endsWith('/nasa-relief.jpg')&&r.status===200),'Real NASA relief texture requested')
 await shoot(page,'moon-after-desktop-overview-relief')
 await page.getByRole('button',{name:'Analizar todo el polo sur',exact:true}).click()
 await page.locator('.candidate-card').first().click()
 const beforeClass=await page.locator('.zone-class').innerText()
 await shoot(page,'moon-after-desktop-overview')
 await page.getByRole('button',{name:'Acercar esta zona',exact:true}).click()
 await page.locator('.polar-quality-note').getByRole('status').filter({hasText:'fuente NASA 80 m'}).waitFor({timeout:45000})
 assert.ok(requests.some(r=>/tile-.*\.u16\.gz$/.test(r.url)&&r.status===200),'Selected-zone LOD downloaded')
 assert.match(await page.locator('.zone-summary').innerText(),/Sin evaluar/)
 await shoot(page,'moon-after-desktop-zoom')
 await page.getByRole('button',{name:'Relieve',exact:true}).click()
 await shoot(page,'moon-after-desktop-zoom-relief')
 assert.equal(await page.locator('.zone-class').innerText(),beforeClass,'Layer and LOD do not change scientific classification')
 await page.getByRole('button',{name:'Volver a todo el polo',exact:true}).click()
 const shackleton=page.locator('.explorer-map .polar-feature-label').filter({hasText:/^Shackleton$/})
 await shackleton.waitFor()
 const labelBox=await shackleton.boundingBox()
 assert.ok(labelBox,'Named lunar crater remains geolocated')
 await page.mouse.click(labelBox.x+labelBox.width/2,labelBox.y+labelBox.height/2)
 await page.getByRole('button',{name:'Acercar esta zona',exact:true}).click()
 await page.locator('.polar-quality-note').getByRole('status').filter({hasText:'fuente NASA 80 m'}).waitFor({timeout:45000})
 await shoot(page,'moon-after-shackleton-detail')
 checks.push('NASA relief texture and selected-zone LOD load; layer changes preserve scientific assessment.')
 const copilot=page.locator('.mission-copilot:visible')
 await copilot.getByRole('button',{name:'Configurar Gemini',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Activar Gemini',exact:true})
 assert.equal(await dialog.getByRole('link',{name:'Google AI Studio ↗',exact:true}).getAttribute('href'),'https://aistudio.google.com/apikey')
 assert.match(await dialog.innerText(),/GEMINI_API_KEY/)
 assert.match(await dialog.innerText(),/Los visitantes.*sin iniciar sesión/)
 assert.equal(await dialog.locator('input,textarea').count(),0,'No key entry form in browser')
 for(const [reason,text] of [['invalid_api_key','no es válida'],['permission_denied','no tiene acceso'],['quota_exceeded','cuota'],['model_not_available','no está disponible'],['provider_unavailable','no responde']]){
  await page.route('**/api/copilot/status',r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify({status:'ok',mode:'guide',available:false,reason})}))
  await dialog.getByRole('button',{name:'Comprobar conexión ahora',exact:true}).click()
  await page.waitForFunction(needle=>document.querySelector('.gemini-setup-status')?.textContent?.includes(needle),text)
  await page.unroute('**/api/copilot/status')
 }
 await dialog.getByRole('button',{name:'Cerrar configuración Gemini',exact:true}).click()
 checks.push('Gemini setup links official key page, explains server-only key and anonymous visitors; recheck diagnoses key, permissions, quota and model.')
 await page.close()
 const failed=await browser.newPage({viewport:{width:1500,height:1050}})
 watch(failed)
 await failed.route('**/data/polar-detail/nasa-relief.jpg',r=>r.fulfill({status:503,body:'optional visual failure'}))
 await failed.route('**/data/polar-detail/tile-*.u16.gz',r=>r.fulfill({status:503,body:'optional tile failure'}))
 await failed.goto(base,{waitUntil:'networkidle'});await ready(failed)
 await failed.getByRole('button',{name:'Analizar todo el polo sur',exact:true}).click()
 await failed.locator('.candidate-card').first().click()
 const known=await failed.locator('.zone-class').innerText()
 await failed.getByRole('button',{name:'Acercar esta zona',exact:true}).click()
 await failed.locator('.polar-quality-note').getByRole('status').filter({hasText:/conserva|sigue disponible/}).waitFor({timeout:45000})
 assert.equal(await failed.locator('.zone-class').innerText(),known)
 assert.match(await failed.locator('.polar-quality-note').innerText(),/sombreado.*(?:no disponible|conservado)|(?:sin sombreado)/i,'Optional shading failure is explicitly disclosed')
 assert.equal(await failed.locator('.candidate-card').count(),3)
 await shoot(failed,'moon-after-optional-data-failure')
 checks.push('Optional texture/tile failure retains regional terrain and identical scientific verdict, with tile fallback disclosed.')
 await failed.close()
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1,reducedMotion:'reduce'})
 watch(mobile)
 await mobile.goto(base,{waitUntil:'networkidle'});await ready(mobile)
 assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
 const map=await mobile.getByTestId('polar-map').boundingBox(),canvas=await mobile.getByTestId('polar-map').locator('canvas').boundingBox()
 assert.ok(Math.abs(map.height-canvas.height)<2)
 await mobile.getByTestId('polar-map').screenshot({path:fileURLToPath(new URL('moon-after-mobile-overview.png',out))})
 await mobile.screenshot({path:fileURLToPath(new URL('moon-after-mobile.png',out)),fullPage:true})
 checks.push('390 px mobile keeps full-height lunar canvas and no horizontal clipping.')
 await mobile.close()
 assert.deepEqual(errors,[])
 const result={base,errors,checks,visualRequests:requests}
 await writeFile(new URL('mission-polish-after.json',out),JSON.stringify(result,null,2))
 console.log(checks.map(c=>'PASS '+c).join('\n'))
 console.log('VISUAL REQUESTS '+JSON.stringify(requests))
}finally{await browser.close()}
