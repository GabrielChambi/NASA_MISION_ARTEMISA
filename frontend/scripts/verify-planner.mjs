import {openReferencePlanner} from './browser-helpers.mjs'
import {chromium} from 'playwright'
import assert from 'node:assert/strict'
import {mkdir,readFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'

const base=process.env.LUNAR_ORACLE_TEST_URL||'http://127.0.0.1:4173/'
const out=new URL('../../artifacts/',import.meta.url)
await mkdir(out,{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true})
const page=await browser.newPage({viewport:{width:1500,height:1100},reducedMotion:'reduce'})
page.setDefaultTimeout(30000)
const errors=[],requests=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('request',r=>{if(/\/api\/(solar|earth)\?/.test(r.url()))requests.push(r.url())})
const state=page.getByTestId('mission-data-status')
const ready=()=>page.waitForFunction(()=>document.querySelector('[data-testid="mission-data-status"]')?.getAttribute('data-state')==='ready',{},{timeout:180000})
const range=async(label,value)=>page.getByLabel(label,{exact:true}).evaluate((el,v)=>{
  const setter=Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set
  setter.call(el,String(v));el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}))
},value)
const done=async(label)=>{const max=await page.getByLabel(label,{exact:true}).getAttribute('max');await range(label,Number(max))}
try {
  await page.goto(base,{waitUntil:'domcontentloaded'});await openReferencePlanner(page);await ready()
  assert.match(await page.title(),/Planificador/)
  assert.equal(await page.getByTestId('comparison-site01').count(),1)
  assert.equal(await page.getByTestId('comparison-site04').count(),1)
  assert.match(await page.getByTestId('comparison-site01').innerText(),/29.0 h/)
  assert.match(await page.getByTestId('comparison-site04').innerText(),/32.74°/)
  const initialTime=await page.getByTestId('conditions-utc').innerText()
  const initialSolar=await page.getByTestId('instant-solar').locator('[data-value=elevation]').innerText()
  await range('Hora de las condiciones',24)
  assert.notEqual(await page.getByTestId('conditions-utc').innerText(),initialTime)
  assert.notEqual(await page.getByTestId('instant-solar').locator('[data-value=elevation]').innerText(),initialSolar)
  assert.match(await page.locator('.atlas-timeline time').innerText(),/2026-12-15/)
  console.log('PASS: aligned NASA UTC changes both map and scientific readouts')
  await page.getByLabel('Margen sobre horizonte · Tierra',{exact:true}).fill('5')
  assert.match(await page.getByTestId('comparison-site01').innerText(),/Tierra\s+0.0 h/)
  assert.match(await page.getByTestId('mission-ranking').innerText(),/Ningún punto/)
  await page.getByLabel('Margen sobre horizonte · Tierra',{exact:true}).fill('0')
  const beforeSelection=requests.length
  await page.getByTestId('comparison-site04').click()
  assert.equal(await page.getByLabel('Punto de estudio',{exact:true}).inputValue(),'site04')
  assert.match(await page.getByTestId('instant-earth').innerText(),/Tierra/)
  await page.getByLabel('Punto de estudio',{exact:true}).selectOption('site01')
  await page.waitForTimeout(300)
  assert.equal(requests.length,beforeSelection)
  console.log('PASS: selection reuses the same mission, and changing Earth margin recalculates windows')
  await range('Hora de las condiciones',0)
  await page.getByRole('button',{name:'Simular descenso',exact:true}).click()
  await page.getByLabel('Pausar descenso en mapa',{exact:true}).click()
  const target=page.getByTestId('map-landing-target')
  assert.equal(Number(await target.getAttribute('data-latitude')),-89.46315776)
  await range('Tiempo del descenso en mapa',40)
  assert.match(await target.innerText(),/Propelente/)
  const mid=await page.locator('.planner-telemetry').innerText()
  assert.doesNotMatch(mid,/—/)
  assert.ok(!mid.includes('2000.0'))
  await done('Tiempo del descenso en mapa')
  await page.waitForFunction(()=>document.querySelector('[data-testid="map-landing-target"]')?.textContent.includes('CONTACTO CON LA SUPERFICIE'))
  assert.match(await page.getByTestId('descent-outcome').innerText(),/Contacto a/)
  assert.match(await target.innerText(),/Altura 0.0 m/)
  await page.waitForTimeout(1200)
  await page.locator('.atlas-viewport').screenshot({path:fileURLToPath(new URL('planner-touchdown.png',out))})
  const evidencePromise=page.waitForEvent('download')
  await page.getByRole('button',{name:'Descargar evidencia',exact:true}).click()
  const evidence=await evidencePromise
  await evidence.saveAs(fileURLToPath(new URL('verified-mission.json',out)))
  const report=JSON.parse(await readFile(await evidence.path(),'utf8'))
  assert.equal(report.studies.length,2);assert.equal(report.descent.run.outcome,'soft-touchdown')
  assert.ok(report.descent.run.samples.length>600)
  assert.ok(report.studies.every(s=>s.solar.meta.query_url.includes('horizons')&&s.earth.meta.query_url.includes('horizons')))
  console.log('PASS: actual descent telemetry, exact mapped contact and reproducible JSON evidence')
  await page.locator('.planner-engine summary').click()
  await page.getByLabel('Empuje máximo',{exact:true}).fill('0')
  await page.getByRole('button',{name:'Simular descenso',exact:true}).click()
  await done('Tiempo del descenso en mapa')
  await page.waitForFunction(()=>document.querySelector('[data-testid="map-landing-target"]')?.textContent.includes('IMPACTO EN EL MODELO'))
  assert.match(await page.getByTestId('descent-outcome').innerText(),/Impacto a/)
  await page.getByLabel('Punto de estudio',{exact:true}).selectOption('site04')
  assert.equal(await target.count(),0)
  console.log('PASS: insufficient thrust produces impact, and changing target clears previous flight')
  await page.getByLabel('Punto de estudio',{exact:true}).selectOption('site01')
  await page.getByLabel('Inicio de misión UTC',{exact:true}).fill('2026-12-14T12:00')
  await page.getByLabel('Fin de misión UTC',{exact:true}).fill('2026-12-17T12:00')
  assert.equal(await state.getAttribute('data-state'),'dirty')
  assert.equal(await page.getByRole('button',{name:'Simular descenso',exact:true}).isDisabled(),true)
  await page.getByRole('button',{name:'Calcular con NASA',exact:true}).click()
  await ready()
  assert.match(await page.getByTestId('conditions-utc').innerText(),/2026-12-14 12:00/)
  assert.notEqual(await page.getByTestId('instant-solar').locator('[data-value=elevation]').innerText(),initialSolar)
  assert.match(await page.getByTestId('scenario-difference').innerText(),/Qué cambió/)
  assert.ok(requests.some(s=>new URL(s).searchParams.get('start_utc')==='2026-12-14T12:00:00.000Z'))
  console.log('PASS: date change issues exact new NASA queries and compares with previous scenario')
  await page.route('**/api/solar?**',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({status:'unavailable',message:'NASA temporalmente no disponible (prueba de fallo)'})}))
  await page.getByRole('button',{name:'Calcular con NASA',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('[data-testid="mission-data-status"]')?.getAttribute('data-state')==='error')
  assert.equal(await page.getByTestId('comparison-site01').count(),0)
  assert.equal(await page.getByRole('button',{name:'Simular descenso',exact:true}).isDisabled(),true)
  assert.match(await page.getByTestId('instant-solar').innerText(),/Sin datos/)
  await page.unroute('**/api/solar?**')
  await page.getByRole('button',{name:'Reintentar',exact:true}).click();await ready()
  console.log('PASS: NASA failure removes stale metrics and prevents starting a flight')
  for (const width of [390,360,768,1500]) {
    await page.setViewportSize({width,height:width>1000?1100:844})
    await page.reload({waitUntil:'domcontentloaded'});await openReferencePlanner(page);await ready()
    await page.evaluate(()=>window.scrollTo(0,0))
    await page.waitForTimeout(1200)
    if(width===390)assert.ok(await page.locator('.planner-map-anchor').evaluate(el=>el.getBoundingClientRect().top<600),'Map must appear before the long form on mobile')
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)
    assert.equal(overflow,false,'horizontal overflow at '+width)
    if(width===390)await page.locator('.atlas-viewport').screenshot({path:fileURLToPath(new URL('planner-map-mobile.png',out))})
    await page.screenshot({path:fileURLToPath(new URL('planner-'+width+'.png',out)),fullPage:true})
  }
  assert.deepEqual(errors,[])
  console.log('PASS: responsive 360 / 390 / 768 / 1500 and no browser exceptions')
} finally {await browser.close()}
