import {openLocalCockpit} from './browser-helpers.mjs'
import { chromium } from 'playwright'
import { mkdir,writeFile,readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import assert from 'node:assert/strict'
const base=process.env.LUNAR_ORACLE_TEST_URL||'http://127.0.0.1:4173/'
const out=new URL('../../artifacts/',import.meta.url)
await mkdir(out,{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true})
const errors=[],log=[]
const watch=page=>page.on('pageerror',e=>errors.push(e.message))
const ready=page=>page.waitForFunction(()=>document.querySelector('[data-testid=assessment-status]')?.textContent?.includes('Criterios geométricos'),null,{timeout:60000})
const range=async(page,value)=>page.getByLabel('Instante de misión',{exact:true}).evaluate((el,v)=>{
  Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,String(v))
  el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}))
},value)
const shot=(page,name)=>page.screenshot({path:fileURLToPath(new URL(name,out)),fullPage:true})
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'})
  watch(page)
  await page.goto(base,{waitUntil:'networkidle'});await openLocalCockpit(page)
  await page.locator('.criteria-details summary').click();await page.locator('.coordinate-details summary').click()
  const simulate=page.getByRole('button',{name:'ANALIZAR SOL Y TIERRA',exact:true})
  await simulate.waitFor()
  await page.waitForFunction(()=>!document.querySelector('.simulate-button')?.disabled)
  assert.match(await page.getByTestId('assessment-status').innerText(),/Ejecuta/)
  assert.equal(await page.getByRole('button',{name:'Descargar evidencia JSON',exact:true}).isDisabled(),true)
  await simulate.click();await ready(page)
  assert.match(await page.locator('.body-readout').first().innerText(),/259.18/)
  assert.match(await page.locator('.body-readout.earth').innerText(),/-1.44/)
  log.push('Exact NASA Sun/Earth, no synthetic initial verdict')
  await range(page,48)
  await page.waitForFunction(()=>document.querySelector('.timeline-controls strong')?.textContent==='+48 h')
  const legend=await page.getByLabel('Leyenda de aptitud').innerText();assert.ok(Number(legend.match(/Cumple · (\d+)/)[1])>0);assert.ok(Number(legend.match(/No cumple · (\d+)/)[1])>0)
  await page.getByRole('button',{name:'Mapa',exact:true}).click()
  await shot(page,'landing-contours-production.png')
  await page.getByRole('button',{name:'Contexto',exact:true}).click();await page.locator('.science-map .polar-feature-label').first().waitFor();await page.getByRole('button',{name:'Mapa',exact:true}).click()
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'Descargar evidencia JSON',exact:true}).click()
  const download=await downloadEvent,path=fileURLToPath(new URL('landing-evidence.json',out))
  await download.saveAs(path)
  const record=JSON.parse(await readFile(path,'utf8'))
  assert.equal(record.assessments.length,441)
  assert.equal(record.display_vertical_exaggeration,1)
  assert.equal(Object.keys(record.source_sha256).length,7)
  assert.equal(record.current_utc,'2026-12-16T00:00:00Z')
  assert.ok(record.sun.meta.query_url.includes('SITE_COORD'))
  log.push('Green/yellow/red contours update with NASA UTC; export includes full provenance')
  await page.getByRole('button',{name:'Evidencia NASA',exact:true}).click()
  const dialog=page.getByRole('dialog')
  assert.match(await dialog.innerText(),/site01:10:10/)
  assert.match(await dialog.innerText(),/2026-12-14/)
  assert.equal(await dialog.locator('a').count(),5)
  await dialog.getByRole('button',{name:'Cerrar',exact:true}).click()
  await page.getByRole('button',{name:'Simular descenso físico',exact:true}).click()
  await page.getByLabel('Velocidad del ensayo').selectOption('60')
  await page.waitForFunction(()=>document.querySelector('.touchdown-status')?.textContent?.includes('CONTACTO SUAVE'),null,{timeout:15000})
  const impact=Number((await page.locator('.touchdown-status').innerText()).match(/([\d.]+) m\/s/)[1]);assert.ok(impact>0&&impact<=2)
  await shot(page,'landing-touchdown-production.png')
  log.push('RK4 descent animates and contacts selected lunar coordinates with changing telemetry')
  for(let i=0;i<3;i++){
    await page.getByRole('button',{name:'Comparar referencias',exact:true}).click()
    await page.getByRole('button',{name:'Volver al cockpit'}).waitFor()
    await page.getByRole('heading',{name:/Tu próximo paso/}).waitFor()
    await page.getByRole('button',{name:'Volver al cockpit'}).click()
    assert.equal(await page.getByLabel('Inicio UTC',{exact:true}).inputValue(),'2026-12-14T00:00')
    assert.match(await page.getByTestId('assessment-status').innerText(),/Criterios geométricos/)
  }
  log.push('View switching preserves case and renderer lifecycle without page exceptions')
  await page.getByLabel('Pendiente máxima',{exact:true}).fill('12')
  assert.match(await page.getByTestId('assessment-status').innerText(),/Cambios sin simular/)
  assert.equal(await page.getByRole('button',{name:'Descargar evidencia JSON',exact:true}).isDisabled(),true)
  await page.getByLabel('Inicio UTC',{exact:true}).fill('')
  await simulate.click()
  assert.match(await page.getByRole('alert').innerText(),/Completa la fecha/)
  log.push('Changed inputs invalidate results; empty UTC fails explicitly')
  await page.getByLabel('Latitud',{exact:true}).fill('')
  await page.getByRole('button',{name:'Localizar en rejilla NASA'}).click()
  assert.match(await page.getByRole('alert').innerText(),/campo vacío/)
  await page.getByLabel('Latitud',{exact:true}).fill('-89.7')
  await page.getByLabel('Longitud este',{exact:true}).fill('-160')
  await page.getByRole('button',{name:'Localizar en rejilla NASA'}).click()
  assert.match(await page.getByRole('alert').innerText(),/Fuera de/)
  assert.equal(await simulate.isDisabled(),true)
  log.push('Uncovered locations remain unknown, including former fictional rescue point')
  await page.close()
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1})
  watch(mobile)
  await mobile.goto(base,{waitUntil:'networkidle'});await openLocalCockpit(mobile)
  for(const name of ['Evidencia NASA','Comparar referencias','Relieve','Mapa','Superficie','Contexto']){
    const b=mobile.getByRole('button',{name,exact:true}),box=await b.boundingBox()
    assert.ok(box&&box.x>=0&&box.x+box.width<=390,name+' clipped')
  }
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await mobile.waitForFunction(()=>{const m=document.querySelector('.science-map'),c=m?.querySelector('canvas');return m&&c&&Math.abs(m.getBoundingClientRect().height-c.getBoundingClientRect().height)<2})
  const mapBox=await mobile.getByTestId('lunar-map').boundingBox(),canvasBox=await mobile.locator('.science-map canvas').first().boundingBox();assert.ok(Math.abs(mapBox.height-canvasBox.height)<2,'Mobile canvas must fill its map')
  await mobile.getByRole('button',{name:'ANALIZAR SOL Y TIERRA',exact:true}).click()
  await ready(mobile)
  await shot(mobile,'landing-mobile-production.png')
  log.push('390 px mobile: navigation, map controls and results usable without horizontal clipping')
  await mobile.close()
  for(const failPath of ['**/api/landing/surface','**/data/polar-atlas/manifest.json','**/api/landing/ephemeris?*']){
    const failed=await browser.newPage({viewport:{width:1280,height:900}})
    watch(failed)
    await failed.route(failPath,r=>r.fulfill({status:503,contentType:'application/json',body:JSON.stringify({status:'unavailable',message:'NASA unavailable regression'})}))
    await failed.goto(base,{waitUntil:'networkidle'});await openLocalCockpit(failed)
    if(failPath.includes('ephemeris'))await failed.getByRole('button',{name:'ANALIZAR SOL Y TIERRA',exact:true}).click()
    await failed.getByRole('alert').waitFor()
    assert.doesNotMatch(await failed.getByTestId('assessment-status').innerText(),/Cumple el modelo/)
    assert.equal(await failed.getByRole('button',{name:'Descargar evidencia JSON',exact:true}).isDisabled(),true)
    await failed.close()
  }
  log.push('Terrain, basemap and NASA upstream failures never retain a positive verdict')
  assert.deepEqual(errors,[])
  await writeFile(new URL('landing-browser-verification.json',out),JSON.stringify({base,errors,checks:log},null,2))
  console.log(log.map(s=>'PASS '+s).join('\n'))
}finally{await browser.close()}
