import {chromium} from 'playwright'
import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'

const base=process.env.LUNAR_ORACLE_TEST_URL||'http://127.0.0.1:5173/'
const out=new URL('../../artifacts/',import.meta.url)
await mkdir(out,{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'})
page.setDefaultTimeout(30000)
const errors=[];page.on('pageerror',e=>errors.push(e.message))
const screenshot=async name=>page.locator('.atlas-viewport').screenshot({path:fileURLToPath(new URL(name+'.png',out))})
try{
  await page.goto(base,{waitUntil:'domcontentloaded'})
  await page.getByRole('button',{name:'Explore NASA data',exact:true}).click()
  const atlas=page.getByRole('region',{name:'NASA lunar south pole 3D terrain atlas'})
  await atlas.getByRole('button',{name:'Inspect lunar feature Shackleton',exact:true}).waitFor()
  await atlas.getByRole('button',{name:'Inspect lunar feature Mons Mouton',exact:true}).waitFor()
  await atlas.locator('.atlas-timeline time').filter({hasText:'UTC'}).waitFor()
  const manifest=await (await page.request.get(new URL('/data/polar-atlas/manifest.json',base).href)).json()
  assert.equal(manifest.source_resolution_m,80)
  assert.equal(manifest.grid_size,769)
  assert.ok(manifest.features.length>=12)
  const binary=await (await page.request.get(new URL(manifest.data_url,base).href)).body()
  assert.equal(binary.length,manifest.grid_size**2*2)
  await page.waitForTimeout(1700)
  await screenshot('polar-atlas-desktop')
  await atlas.getByRole('button',{name:'Inspect lunar feature Shackleton',exact:true}).click()
  assert.equal(await atlas.getByRole('heading',{name:'Shackleton',exact:true}).isVisible(),true)
  assert.ok((await atlas.getByRole('link',{name:'Official nomenclature'}).getAttribute('href')).includes('planetarynames.wr.usgs.gov/Feature/5450'))
  await atlas.getByRole('button',{name:'Close feature details'}).click()
  await atlas.getByRole('button',{name:'Monochrome relief',exact:true}).click()
  assert.equal(await atlas.getByRole('button',{name:'Monochrome relief',exact:true}).getAttribute('aria-pressed'),'true')
  await atlas.getByRole('combobox',{name:'Vertical exaggeration'}).selectOption('1')
  assert.equal(await atlas.getByText('Vertical display: 1×',{exact:false}).isVisible(),true)
  await screenshot('polar-atlas-true-scale')
  await atlas.getByRole('button',{name:'Polar view',exact:true}).click()
  await page.waitForTimeout(1600)
  await screenshot('polar-atlas-polar')
  await atlas.getByRole('button',{name:'Feature labels',exact:true}).click()
  assert.equal(await atlas.locator('.atlas-crater-label').count(),0)
  await atlas.getByRole('button',{name:'Feature labels',exact:true}).click()
  await atlas.locator('.atlas-site-strip').getByRole('button',{name:/Connecting ridge/}).click()
  assert.equal(await page.getByLabel('Primary study region',{exact:true}).inputValue(),'site01')
  await atlas.getByRole('button',{name:'Focus region',exact:true}).click()
  await page.waitForTimeout(1600)
  await screenshot('polar-atlas-focus')
  await atlas.getByRole('button',{name:'Sun & Earth',exact:true}).click()
  assert.equal(await atlas.getByRole('button',{name:'Sun & Earth',exact:true}).getAttribute('aria-pressed'),'true')
  const slider=atlas.getByRole('slider',{name:'Terrain ephemeris time'})
  await slider.fill('24')
  assert.ok((await atlas.locator('.atlas-timeline time').innerText()).includes('2026-12-15'))
  await atlas.getByRole('button',{name:'Reset terrain view'}).click()
  await atlas.getByRole('button',{name:'Elevation color',exact:true}).click()
  await atlas.getByLabel('Vertical exaggeration').selectOption('3')
  await page.setViewportSize({width:390,height:844})
  await page.waitForTimeout(1800)
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth))
  await screenshot('polar-atlas-mobile')
  assert.equal(await atlas.getByRole('button',{name:'Inspect lunar feature Shackleton',exact:true}).isVisible(),true)
  await page.setViewportSize({width:1440,height:1100})
  await atlas.getByRole('button',{name:'Reset terrain view'}).click()
  const canvas=atlas.getByRole('img',{name:/NASA LOLA south pole terrain/})
  await canvas.scrollIntoViewIfNeeded()
  await page.waitForTimeout(1200)
  const before=await canvas.screenshot()
  const box=await canvas.boundingBox()
  await page.mouse.move(box.x+box.width*.53,box.y+box.height*.55)
  await page.mouse.down();await page.mouse.move(box.x+box.width*.64,box.y+box.height*.58,{steps:10});await page.mouse.up()
  await page.waitForTimeout(1000)
  assert.notEqual((await canvas.screenshot()).toString('base64'),before.toString('base64'),'Dragging must change the real 3D viewpoint')
  assert.deepEqual(errors,[])
  console.log('PASS NASA polar atlas: measured binary integrity, named geographic features, inspection, both color modes, true-scale view, polar/region cameras, labels, synchronized site selection, real UTC timeline, mobile layout, and interactive orbit. No runtime errors.')
}finally{await browser.close()}
